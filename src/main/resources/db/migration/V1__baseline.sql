-- Baseline of the current JPA schema.
-- Empty databases run this script. A non-empty database with no Flyway
-- history is baselined at version 1 and skips it.

create table users (
    id bigint generated by default as identity,
    first_name varchar(255) not null,
    last_name varchar(255) not null,
    email varchar(255) not null,
    password varchar(255) not null,
    verified boolean not null,
    constraint users_pkey primary key (id),
    constraint users_email_key unique (email)
);

create table authorization_tokens (
    id bigint generated by default as identity,
    token varchar(255) not null,
    revoked boolean not null,
    user_id bigint,
    constraint authorization_tokens_pkey primary key (id),
    constraint fk_authorization_tokens_user foreign key (user_id) references users (id)
);

create table deposit_wallets (
    id bigint generated by default as identity,
    address varchar(255) not null,
    asset_id varchar(255) not null,
    balance numeric(38, 7) not null,
    locked_balance numeric(38, 7) not null,
    opened_at timestamp(6) not null,
    accrued_interest numeric(38, 7) not null,
    user_id bigint,
    constraint deposit_wallets_pkey primary key (id),
    constraint fk_deposit_wallets_user foreign key (user_id) references users (id)
);

create table email_verification_tokens (
    id bigint generated by default as identity,
    token varchar(255) not null,
    expires_at timestamp(6) not null,
    used boolean not null,
    user_id bigint,
    constraint email_verification_tokens_pkey primary key (id),
    constraint email_verification_tokens_token_key unique (token),
    constraint fk_email_verification_tokens_user foreign key (user_id) references users (id)
);

create table loans (
    id bigint generated by default as identity,
    loan_asset_id varchar(255) not null,
    returned_amount numeric(38, 7) not null,
    amount numeric(38, 7) not null,
    collateral_asset_id varchar(255) not null,
    collateral_amount numeric(38, 7) not null,
    current_collateral numeric(38, 7) not null,
    interest_rate numeric(10, 6) not null,
    accrued_interest numeric(38, 2) not null,
    granted_at timestamp(6) not null,
    user_id bigint,
    constraint loans_pkey primary key (id),
    constraint fk_loans_user foreign key (user_id) references users (id)
);

create table funds_transfers (
    id bigint generated by default as identity,
    amount numeric(38, 7) not null,
    timestamp timestamp(6) not null,
    transaction_id varchar(255),
    counterparty_address varchar(255) not null,
    is_completed boolean not null,
    wallet_id bigint,
    constraint funds_transfers_pkey primary key (id),
    constraint fk_funds_transfers_wallet foreign key (wallet_id) references deposit_wallets (id)
);
